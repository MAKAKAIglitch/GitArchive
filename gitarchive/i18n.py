"""Automatic Russian / English localization for GitArchive."""
from __future__ import annotations

import ctypes
import locale
import os
import re
import sys


def detect_system_language() -> str:
    """Use the user's Windows UI language; use the process locale elsewhere."""
    if sys.platform == "win32":
        try:
            kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
            kernel32.GetUserDefaultUILanguage.restype = ctypes.c_ushort
            language_id = int(kernel32.GetUserDefaultUILanguage())
            if language_id:
                return "en" if (language_id & 0x03FF) == 0x0009 else "ru"
        except (AttributeError, OSError, ValueError):
            pass

    candidates = [
        os.environ.get("LC_ALL", ""),
        os.environ.get("LC_MESSAGES", ""),
        os.environ.get("LANG", ""),
    ]
    try:
        current = locale.getlocale()[0]
        if current:
            candidates.insert(0, current)
    except (ValueError, TypeError):
        pass
    language = next((value for value in candidates if value), "ru")
    return "en" if language.lower().replace("-", "_").startswith("en") else "ru"


