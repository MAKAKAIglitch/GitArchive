def tr(value: str, language: str | None = None) -> str:
    """Translate a Russian UI/log string when English is the system UI language."""
    selected_language = LANGUAGE if language is None else str(language).lower()
    if not isinstance(value, str):
        return value
    if selected_language == "ru":
        return _REVERSE_TRANSLATIONS.get(value, value)
    if selected_language != "en":
        return value
    translated = _TRANSLATIONS.get(value)
    if translated is not None:
        return translated
    # Some interpolated strings contain a localized fallback value inside an f-string.
    value = value.replace("неизвестный репозиторий", "unknown repository")
    for pattern, template in _DYNAMIC:
        match = pattern.match(value)
        if match:
            try:
                return template.format(*match.groups())
            except (IndexError, KeyError, ValueError):
                return value
    return value


